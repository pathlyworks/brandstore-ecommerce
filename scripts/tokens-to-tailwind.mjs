/**
 * Brand tokens -> Tailwind CSS v4 theme. Reads the :root custom properties in css/base.css (the legacy
 * app's single source of design tokens) and writes docs/migration/tailwind-theme.css: an `@theme` block
 * in Tailwind's namespaces, plus a table of every token and where it went.
 *   node scripts/tokens-to-tailwind.mjs
 * In wave 0 the same script writes the React app's theme file, so the brand stays defined once.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const css = readFileSync('css/base.css', 'utf8');
const root = css.slice(css.indexOf(':root {'), css.indexOf('}', css.indexOf(':root {')));
const tokens = [...root.matchAll(/^\s*(--[\w-]+):\s*([^;]+);/gm)].map(([, name, value]) => ({
  name,
  value: value.trim(),
}));

/** [legacy prefix, Tailwind v4 namespace prefix, what it generates]. First match wins. */
const RULES = [
  ['--color-', '--color-', 'bg-*, text-*, border-*, ring-* … (e.g. bg-primary, text-text-muted)'],
  ['--overlay-', '--color-overlay-', 'bg-overlay-dark …'],
  ['--space-', '--spacing-', 'p-*, m-*, gap-* (e.g. p-md, gap-lg)'],
  ['--font-sans', '--font-sans', 'font-sans'],
  ['--text-', '--text-', 'text-sm … text-h1 (fluid clamp() sizes kept)'],
  ['--weight-', '--font-weight-', 'font-medium … font-extrabold'],
  ['--leading-', '--leading-', 'leading-tight …'],
  ['--tracking-', '--tracking-', 'tracking-tight …'],
  ['--radius-', '--radius-', 'rounded-sm, rounded-md, rounded-pill'],
  ['--shadow-', '--shadow-', 'shadow-sm, shadow-md, shadow-lg'],
  ['--ease-', '--ease-', 'ease-standard, ease-out'],
  ['--container-max', '--container-page', 'max-w-page'],
  ['--measure', '--container-measure', 'max-w-measure, max-w-measure-narrow'],
  [
    '--size-',
    '--size-',
    'not a Tailwind namespace: kept as a CSS variable, used as w-(--size-sidebar)',
  ],
  ['--z-', '--z-', 'not a namespace: z-(--z-header)'],
  ['--duration-', '--duration-', 'not a namespace: duration-(--duration-fast)'],
  ['--', '--', 'kept as a CSS variable (component-level value)'],
];

const rows = [];
const theme = [];
const plain = [];
for (const { name, value } of tokens) {
  const [from, to, use] = RULES.find(([prefix]) => name.startsWith(prefix));
  const target = to + name.slice(from.length);
  const inTheme = !use.startsWith('not a') && !use.startsWith('kept');
  (inTheme ? theme : plain).push(
    `  ${target}: ${value.replace(/var\(--color-/g, 'var(--color-')};`,
  );
  rows.push(
    `| \`${name}\` | \`${value}\` | ${inTheme ? `\`${target}\`` : '— (CSS variable)'} | ${use} |`,
  );
}

const out = `/* Generated by scripts/tokens-to-tailwind.mjs from css/base.css — do not edit by hand.
   Tailwind CSS v4: \`@import "tailwindcss";\` then this file. Breakpoints match the legacy 48em / 64em / 90em. */
@theme {
  /* Only brand colours and brand type sizes exist: Tailwind's default palette and sizes are removed, so
     bg-blue-500 or text-4xl do not compile into anything (web/scripts/check-tokens.mjs also bans arbitrary values). */
  --color-*: initial;
  --text-*: initial;
  --breakpoint-md: 48em;
  --breakpoint-lg: 64em;
  --breakpoint-xl: 90em;
${theme.join('\n')}
}

/* Tokens outside Tailwind's namespaces stay CSS variables (use them as w-(--size-sidebar)). */
:root {
${plain.join('\n')}
}
`;
writeFileSync('docs/migration/tailwind-theme.css', out);
writeFileSync('web/src/styles/theme.css', out); // the React app's theme (Advanced Task 2)
writeFileSync(
  'docs/migration/tailwind-tokens.md',
  `# Brand tokens in Tailwind (generated)\n\n${tokens.length} tokens from \`css/base.css\`; ${theme.length} become Tailwind theme variables, ${plain.length} stay CSS variables. Generated by \`node scripts/tokens-to-tailwind.mjs\`; the theme itself is \`docs/migration/tailwind-theme.css\`.\n\n| Legacy token | Value | Tailwind v4 theme variable | Utilities |\n| :--- | :--- | :--- | :--- |\n${rows.join('\n')}\n`,
);
console.log(
  `${tokens.length} tokens: ${theme.length} in @theme, ${plain.length} kept as CSS variables`,
);
