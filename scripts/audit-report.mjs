/**
 * npm audit, with a written policy (task_4_security.md §6):
 * - production dependencies (what ships to browsers: react, react-dom, react-router; axios in the legacy
 *   pages): any advisory of moderate severity or above fails, unless security/audit-allowlist.json lists it
 *   with a reason and an expiry date;
 * - development dependencies (build, test and lint tools that never ship): critical fails, the rest is
 *   reported, each one to be listed in the allowlist with how it is handled.
 * An allowlist entry past its expiry date fails too, so every exception is looked at again.
 *
 * Run: npm run audit (needs the npm registry). Writes security/npm-audit-report.md.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const SEVERITY = { info: 0, low: 1, moderate: 2, high: 3, critical: 4 };

function audit(args) {
  try {
    return JSON.parse(
      execFileSync('npm', ['audit', '--json', ...args], {
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'pipe'],
      }),
    );
  } catch (error) {
    // npm audit exits 1 when it finds something; the JSON is still on stdout.
    if (error.stdout) return JSON.parse(error.stdout);
    throw error;
  }
}

/** One row per advisory: package, severity, title, url, the range, whether a fix exists. */
function advisories(report) {
  const rows = new Map();
  for (const [name, v] of Object.entries(report.vulnerabilities ?? {})) {
    for (const via of v.via) {
      if (typeof via !== 'object') continue; // "via": "other-package" = inherited, listed under that package
      rows.set(via.url, {
        id: via.url,
        package: name,
        severity: via.severity,
        title: via.title,
        range: via.range,
        fix:
          v.fixAvailable === true
            ? 'npm audit fix'
            : v.fixAvailable
              ? `upgrade ${v.fixAvailable.name} to ${v.fixAvailable.version}`
              : 'no fix yet',
      });
    }
  }
  return [...rows.values()].sort((a, b) => SEVERITY[b.severity] - SEVERITY[a.severity]);
}

const all = advisories(audit([]));
const prodIds = new Set(advisories(audit(['--omit=dev'])).map((a) => a.id));
const allow = JSON.parse(readFileSync('security/audit-allowlist.json', 'utf8')).entries;
const today = new Date().toISOString().slice(0, 10);
const failures = [];

const rows = all.map((a) => {
  const scope = prodIds.has(a.id) ? 'production' : 'development';
  const entry = allow.find((e) => e.id === a.id);
  const limit = scope === 'production' ? SEVERITY.moderate : SEVERITY.critical;
  let status = 'reported';
  if (entry && entry.expires < today) {
    status = `allowlist entry expired ${entry.expires}`;
    failures.push(`${a.package}: ${status}`);
  } else if (entry) status = `allowed until ${entry.expires}: ${entry.reason}`;
  else if (SEVERITY[a.severity] >= limit) {
    status = 'FAILS the policy';
    failures.push(`${a.package} (${a.severity}, ${scope}): ${a.title} ${a.id}`);
  } else if (scope === 'development')
    status = 'reported (development only); add it to the allowlist with how it is handled';
  return { ...a, scope, status };
});
const stale = allow.filter((e) => !all.some((a) => a.id === e.id));

const lines = [
  '# npm audit report',
  '',
  `Generated by \`npm run audit\` on ${today}. Policy: task_4_security.md §6.`,
  '',
  rows.length === 0
    ? 'No advisories.'
    : [
        '| Package | Severity | Scope | Advisory | Fix | Status |',
        '| :-- | :-- | :-- | :-- | :-- | :-- |',
      ]
        .concat(
          rows.map(
            (r) =>
              `| ${r.package} | ${r.severity} | ${r.scope} | [${r.title}](${r.id}) | ${r.fix} | ${r.status} |`,
          ),
        )
        .join('\n'),
  '',
  stale.length
    ? `Allowlist entries no longer needed (remove them): ${stale.map((e) => e.id).join(', ')}`
    : '',
];
writeFileSync('security/npm-audit-report.md', `${lines.join('\n').trim()}\n`);
console.log(lines.join('\n'));
if (failures.length) {
  console.error(`\nnpm audit policy failed:\n- ${failures.join('\n- ')}`);
  process.exit(1);
}
