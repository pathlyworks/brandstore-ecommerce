/**
 * Writes src/types/__checks__/observed.ts: every response captured in docs/migration/observed/ assigned to
 * its type from src/types/api.ts. `npm run typecheck` then fails if a type misses a field the API sends
 * (excess property), requires one it sometimes leaves out, or has the wrong JSON type.
 *   node scripts/gen-observed-types-check.mjs     (after node scripts/capture-api.mjs)
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const DIR = 'docs/migration/observed';
const TYPE_FOR = [
  [/^categories/, 'ApiCategory[]'],
  [/^products-(page|filtered|search)/, 'ProductPage'],
  [/^product-p-/, 'ApiProduct'],
  [/^(login-shopper|login-admin|register-ok)$/, 'Session'],
  [/^orders-(page|offset)/, 'OrderPage'],
  [/^order-cancel-ok$/, 'ApiOrder'],
  [/^addresses$/, 'ApiAddress[]'],
  [/^address-put-ok$/, 'ApiAddress'],
  [/^order-place-ok$/, 'PlacedOrder'],
  [/^admin-summary$/, 'AdminSummary'],
  [/^image-/, 'ImageStub'],
];
const camel = (s) => s.replace(/-(\w)/g, (_, c) => c.toUpperCase()).replace(/^(\d)/, '_$1');
const used = new Set(['ApiError', 'ObservedStatus']);
const lines = [];
for (const file of readdirSync(DIR)
  .filter((f) => f.endsWith('.json') && f !== 'index.json')
  .sort()) {
  const name = file.replace(/\.json$/, '');
  const { status, body } = JSON.parse(readFileSync(`${DIR}/${file}`, 'utf8'));
  const type =
    status === 204
      ? 'null'
      : (TYPE_FOR.find(([re]) => re.test(name))?.[1] ?? (status >= 400 ? 'ApiError' : null));
  if (!type) throw new Error(`No type for ${name} (${status})`);
  const ok = status >= 400 && type !== 'ImageStub' ? 'ApiError' : type;
  used.add(ok.replace('[]', ''));
  lines.push(
    `/** ${name}.json: HTTP ${status} */\nexport const ${camel(name)}: ${ok} = ${JSON.stringify(body, null, 2)};\nexport const ${camel(name)}Status: ObservedStatus = ${status};\n`,
  );
}
const imports = [...used].filter((t) => t !== 'null').sort();
writeFileSync(
  'src/types/__checks__/observed.ts',
  `// Generated by scripts/gen-observed-types-check.mjs from docs/migration/observed/ — do not edit.\n// Each captured response, assigned to its type: npm run typecheck fails if the types and the API disagree.\nimport type { ${imports.join(', ')} } from '../api';\n\n${lines.join('\n')}`,
);
execFileSync('npx', ['prettier', '--write', 'src/types/__checks__/observed.ts'], {
  stdio: 'ignore',
});
console.log(`${lines.length} responses checked against ${imports.length} types`);
