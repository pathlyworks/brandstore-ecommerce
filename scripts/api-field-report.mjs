/**
 * Field inventory of the captured TechSphere responses (docs/migration/observed/): for every entity, each
 * field with the JSON types seen and how many records have it. The TypeScript types in src/types/api.ts are
 * written from this table (a field present in every record is required; in some, optional; several types,
 * a union). Writes docs/migration/observed-fields.md.
 *   node scripts/api-field-report.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const DIR = 'docs/migration/observed';
const read = (name) => JSON.parse(readFileSync(join(DIR, `${name}.json`), 'utf8')).body;
const typeOf = (v) => (v === null ? 'null' : Array.isArray(v) ? 'array' : typeof v);

/** Merge records into { field: { types: Set, count } }, descending one level into objects. */
function inventory(records) {
  const fields = new Map();
  const note = (key, value) => {
    const f = fields.get(key) ?? { types: new Set(), count: 0, examples: new Set() };
    f.types.add(typeOf(value));
    f.count += 1;
    if (f.examples.size < 4 && typeof value !== 'object') f.examples.add(JSON.stringify(value));
    fields.set(key, f);
  };
  for (const record of records) {
    for (const [key, value] of Object.entries(record)) {
      note(key, value);
      if (value && typeof value === 'object' && !Array.isArray(value)) {
        for (const [k, v] of Object.entries(value)) note(`${key}.${k}`, v);
      }
      if (Array.isArray(value) && value[0] && typeof value[0] === 'object') {
        for (const item of value)
          for (const [k, v] of Object.entries(item)) note(`${key}[].${k}`, v);
      } else if (Array.isArray(value)) {
        for (const item of value) note(`${key}[]`, item);
      }
    }
  }
  return fields;
}

function table(title, records, source) {
  const rows = [...inventory(records)].map(
    ([key, f]) =>
      `| \`${key}\` | ${[...f.types].join(' \\| ')} | ${f.count}${key.includes('[]') ? '' : ` / ${records.length}`} | ${[...f.examples].join(', ')} |`,
  );
  return `### ${title}\n\nSource: ${source} (${records.length} records)\n\n| Field | JSON types seen | Present | Examples |\n| :--- | :--- | ---: | :--- |\n${rows.join('\n')}\n`;
}

const products = [1, 2, 3].flatMap((p) => read(`products-page-${p}`).items);
const orders = [...read('orders-page-1').items, ...read('orders-offset-5').items];
const sections = [
  table('Product (GET /products, all 24)', products, 'products-page-1..3'),
  table(
    'Products page envelope',
    [1, 2, 3, 9].map((p) => {
      const { items, ...rest } = read(`products-page-${p}`);
      return { ...rest, items };
    }),
    'products-page-1, 2, 3, 9',
  ),
  table(
    'Category (GET /categories)',
    [...read('categories'), ...read('categories-ar')],
    'categories, categories-ar',
  ),
  table(
    'Session (POST /auth/login, /auth/register)',
    [read('login-shopper'), read('login-admin'), read('register-ok')],
    'login-shopper, login-admin, register-ok',
  ),
  table('Order (GET /account/orders, all 9)', orders, 'orders-page-1, orders-offset-5'),
  table(
    'Orders page envelope',
    [read('orders-page-1'), read('orders-offset-5')].map(({ items, ...r }) => ({ ...r, items })),
    'orders-page-1, orders-offset-5',
  ),
  table('Address (GET /account/addresses)', read('addresses'), 'addresses'),
  table('Placed order (POST /orders 201)', [read('order-place-ok')], 'order-place-ok'),
  table('Admin summary (GET /admin/summary)', [read('admin-summary')], 'admin-summary'),
  table(
    'Error body (every 4xx)',
    [
      'products-bad-sort',
      'product-missing',
      'login-wrong',
      'register-taken',
      'orders-no-token',
      'order-cancel-shipped',
      'address-put-no-city',
      'order-place-empty',
      'admin-summary-shopper',
      'products-429',
      'image-missing',
    ].map(read),
    '11 error responses',
  ),
];
writeFileSync(
  'docs/migration/observed-fields.md',
  `# Observed TechSphere API fields\n\nGenerated by \`node scripts/api-field-report.mjs\` from the responses captured by \`node scripts/capture-api.mjs\`\n(\`docs/migration/observed/\`). "Present" below the record count means the field is sometimes missing.\n\n${sections.join('\n')}`,
);
