/**
 * Writes src/features/cart/cart-reference.json: reference cart totals the app's selectors are tested against
 * (cart.selectors.test.ts), computed here independently of the app's code, in exact decimal arithmetic
 * (BigInt minor units from the price TEXT, never floating point).
 *
 * - "techsphere" cases: products as the TechSphere API really sends them (docs/migration/observed: prices as
 *   numbers and as strings like "EGP 33,999", low stock, missing stock_status, out of stock).
 * - "legacy" cases: tests/fixtures/cart-cases.json (computed with Python's Decimal in Phase 2), with the unit
 *   prices of mock-server/data.mjs, because the TechSphere catalogue never goes below free shipping.
 *
 * Rule: free shipping from 100.00 of subtotal, else 7.99; empty cart 0; out-of-stock lines not charged.
 * Run: node web/scripts/cart-reference.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { PRODUCTS } from '../../mock-server/data.mjs';

const root = fileURLToPath(new URL('../../', import.meta.url));
const read = (path) => JSON.parse(readFileSync(root + path, 'utf8'));

/** "EGP 33,999" | 32999 | "1,299.5" → minor units (BigInt), from the text. */
function minor(price) {
  const text = typeof price === 'number' ? String(price) : price.replace(/[^\d.]/g, '');
  const [whole, frac = ''] = text.split('.');
  return BigInt(whole) * 100n + BigInt((frac + '00').slice(0, 2));
}
const units = (m) => Number(m) / 100; // exact for these magnitudes (2 decimals)
const shipping = (sub) => (sub <= 0n || sub >= 10000n ? 0n : 799n);

const techsphere = ['products-page-1', 'products-page-2', 'products-page-3'].flatMap(
  (page) => read(`docs/migration/observed/${page}.json`).body.items,
);
const byId = new Map(techsphere.map((p) => [p.id, p]));
const STOCK = { in_stock: 25, low: 3, out_of_stock: 0 };

function techCase(name, lines) {
  let sub = 0n;
  let count = 0;
  for (const { productId, quantity } of lines) {
    const p = byId.get(productId);
    const stock = STOCK[p.stock_status] ?? 25; // missing stock_status → treated as available
    const qty = Math.min(quantity, stock, 10);
    if (stock === 0) continue; // kept in the cart, not charged
    sub += minor(p.price) * BigInt(qty);
    count += qty;
  }
  const ship = shipping(sub);
  return {
    name,
    source: 'techsphere',
    lines,
    expected: {
      itemCount: count,
      subtotal: units(sub),
      shipping: units(ship),
      total: units(sub + ship),
    },
  };
}

const cases = [
  techCase('one laptop (number price)', [{ productId: 'p-001', quantity: 1 }]),
  techCase('string price "EGP 33,999", quantity 2', [{ productId: 'p-005', quantity: 2 }]),
  techCase('two string prices and a number price', [
    { productId: 'p-005', quantity: 1 },
    { productId: 'p-014', quantity: 2 },
    { productId: 'p-003', quantity: 3 },
  ]),
  techCase('low stock capped at 3', [{ productId: 'p-002', quantity: 5 }]),
  techCase('missing stock_status, quantity 10', [{ productId: 'p-007', quantity: 10 }]),
  techCase('per-line limit 10', [{ productId: 'p-003', quantity: 12 }]),
  techCase('out-of-stock line not charged', [
    { productId: 'p-004', quantity: 1 },
    { productId: 'p-011', quantity: 2 },
  ]),
  techCase(
    'six lines',
    ['p-001', 'p-006', 'p-009', 'p-015', 'p-018', 'p-022'].map((productId, i) => ({
      productId,
      quantity: (i % 3) + 1,
    })),
  ),
];

const legacy = read('tests/fixtures/cart-cases.json');
const prices = new Map(PRODUCTS.map((p) => [p.id, p]));
for (const c of legacy.cases) {
  cases.push({
    name: `legacy: ${c.name}`,
    source: 'legacy',
    lines: c.lines.map(({ productId, quantity }) => {
      const p = prices.get(productId);
      return {
        productId,
        quantity,
        name: p.name,
        price: (p.price / 100).toFixed(2),
        stock: p.stock,
      };
    }),
    expected: c.expected,
  });
}

writeFileSync(
  fileURLToPath(new URL('../src/features/cart/cart-reference.json', import.meta.url)),
  `${JSON.stringify({ description: 'Generated by web/scripts/cart-reference.mjs. Amounts in currency units; compare within the tolerance.', tolerance: 0.005, cases }, null, 2)}\n`,
);
console.log(`${cases.length} reference cases written`);
